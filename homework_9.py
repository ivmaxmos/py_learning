#1 У пользователя есть все документы из списка обязательных (паспорт, ИНН, СНИЛС).
#2 Равны ли наборы документов
#3 Лишние документы у пользователя
#Проверяется, является ли набор пользовательских документов (userdocs) подмножеством обязательных (requireddocs)


userdocs = frozenset({"паспорт", "ИНН", "СНИЛС", "Диплом"})
requireddocs = {"паспорт", "ИНН", "СНИЛС"}


print(f"1 Все ли: {requireddocs.issubset(userdocs)}")
print(f"1 Равны ли: {requireddocs == set(userdocs)}")
print("3 Лишние: ", userdocs - requireddocs)